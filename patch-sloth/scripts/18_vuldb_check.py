"""Sanity check behind chart 04's VulDB bar (77% of VulDB-scored labelled CVEs put in a higher band by NVD):
5 random bumped examples (description, VulDB vector, NVD vector), the rate by year and split, and which CVSS fields
NVD changed on the bumped rows. Same rows and scorer rule as scripts/08 (score_source CNA, cna = cna@vuldb.com).
Writes results/vuldb_check.md. Usage: python scripts/18_vuldb_check.py"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from patchsloth.cvss import METRICS, base_score, parse, severity  # noqa: E402

R = Path("results")
AS_OF = (R / "data_as_of.txt").read_text().strip()
df = pd.read_parquet("data/cves.parquet")
lab = df[df.split.isin(["train", "val", "test"])]
v = lab[(lab.cna == "cna@vuldb.com") & (lab.score_source != "CISA-ADP")].copy()
v["bump"] = v.bump_up.astype(bool)
v["year"] = v.published.str[:4]
bumped = v[v.bump]


def sev(x):
    s = base_score(parse(x))
    return f"{severity(s)} {s}"


changes = {f: float(np.mean([parse(c)[f] != parse(n)[f] for c, n in zip(bumped.cna_vector, bumped.label_vector)]))
           for f in METRICS}
pairs = pd.Series([f"{sev(c).split()[0]} → {sev(n).split()[0]}" for c, n in zip(bumped.cna_vector, bumped.label_vector)])
cia = pd.Series(["/".join(parse(c)[f] for f in "CIA") + " → " + "/".join(parse(n)[f] for f in "CIA")
                 for c, n in zip(bumped.cna_vector, bumped.label_vector)])
lll = (cia == "L/L/L → H/H/H").to_numpy()
cwe89 = float(bumped.cna_cwe.fillna("").str.contains("CWE-89").to_numpy()[lll].mean())
by_year = v.groupby("year").bump.agg(["size", "mean"])
by_split = v.groupby("split").bump.agg(["size", "mean"]).reindex(["train", "val", "test"])
ex = bumped.sample(5, random_state=0).sort_values("published")

L = ["# VulDB sanity check (chart 04: 77% bump rate)", "",
     f"Data as of {AS_OF}. Rows: labelled CVEs (train+val+test, SPEC §8.2 label rule) whose vector came from VulDB "
     f"(`cna@vuldb.com`, not CISA-ADP), as in `scripts/08_backlog_charts.py`. Generated by "
     "`scripts/18_vuldb_check.py`.", "",
     f"- VulDB-scored labelled CVEs: {len(v):,}; NVD put {len(bumped):,} ({v.bump.mean():.1%}) in a higher band.",
     f"- Every bumped row has an NVD-written vector: {int(bumped.nvd_vector.notna().sum()):,} of {len(bumped):,} "
     "(a bump needs NVD's own vector by the label rule).", "",
     "## Rate by year and split", "", "| | n | bump rate |", "|---|---|---|"]
L += [f"| {y} | {int(r['size']):,} | {r['mean']:.1%} |" for y, r in by_year.iterrows()]
L += [f"| split {s} | {int(r['size']):,} | {r['mean']:.1%} |" for s, r in by_split.iterrows()]
L += ["", "## What NVD changed on the bumped rows", "",
      "Share of bumped rows where NVD's value differs from VulDB's, per field:", "",
      "| " + " | ".join(METRICS) + " |", "|" + "---|" * len(METRICS),
      "| " + " | ".join(f"{changes[f]:.0%}" for f in METRICS) + " |", "",
      "Most common severity changes: " + "; ".join(f"{k} {n:,}" for k, n in pairs.value_counts().head(4).items()) + ".",
      "Most common C/I/A changes (VulDB → NVD): " +
      "; ".join(f"`{k}` {n:,}" for k, n in cia.value_counts().head(5).items()) + ".",
      f"Of the {int(lll.sum()):,} `L/L/L → H/H/H` rows, {cwe89:.1%} carry CWE-89 (SQL injection) in VulDB's CWE list.",
      "",
      "## 5 random bumped examples (seed 0)", ""]
for i, (_, r) in enumerate(ex.iterrows(), 1):
    L += [f"### {i}. {r.cve} (published {r.published}, CWE {r.cna_cwe or '—'})", "",
          "| | Vector | Severity |", "|---|---|---|",
          f"| VulDB | `{r.cna_vector}` | {sev(r.cna_vector)} |",
          f"| NVD | `{r.nvd_vector}` | {sev(r.nvd_vector)} |", "",
          "> " + " ".join(str(r.description).split()), ""]
(R / "vuldb_check.md").write_text("\n".join(L), encoding="utf-8")
print("\n".join(L[:30]))
