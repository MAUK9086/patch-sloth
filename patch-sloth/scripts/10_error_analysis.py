"""Error analysis (SPEC §10): 20 false-positive "likely" flags and 20 false negatives of the served combined model
(stack = TabPFN-3.5 + fine-tuned-LLM features, seed 0; results/serving_stack.json) on the 2026 evaluation test rows
of the frozen snapshot (results/data_as_of.txt). Writes results/error_sample.md for the human to tag [HUMAN].

  false positive  band "likely" (p >= tau, label-free top 10% of Deferred) and NVD did NOT raise the band
  false negative  NVD raised the band, but the band is not "likely" (shown: "possible" or "unlikely")
"Our vector" is what the product serves: the LLM vector if p >= gate t, else the CNA vector (final_table.md §4/§6).
The raw fine-tuned LLM vector is shown as well.

Needs the per-row stack predictions from scripts/12 (data/m4/tabpfn_llm_stack_s0.parquet, GPU workstation).
Usage: python scripts/10_error_analysis.py [--preds data/m4/tabpfn_llm_stack_s0.parquet] [--n 20]"""
import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from patchsloth.cvss import base_score, parse, severity  # noqa: E402

ap = argparse.ArgumentParser()
ap.add_argument("--preds", default="data/m4/tabpfn_llm_stack_s0.parquet")
ap.add_argument("--n", type=int, default=20)
ap.add_argument("--out", default="results/error_sample.md")
a = ap.parse_args()

R = Path("results")
if not Path(a.preds).exists():
    sys.exit(f"{a.preds} not found: it is written by scripts/12_m4_experiments.py on the GPU workstation "
             "(config tabpfn_llm_stack, seed 0). Run this script there, or copy the file here.")
AS_OF = (R / "data_as_of.txt").read_text().strip()
serving = json.loads((R / "serving_stack.json").read_text())
tau, tau_possible, gate_t = serving["tau"], serving["tau_possible"], serving["gate_t"]
llm = json.loads((R / "llm_vectors_ft_test.json").read_text())

pr = pd.read_parquet(a.preds)
pr = pr[pr.split == "test"]
df = pd.read_parquet("data/cves.parquet").set_index("cve")
d = df.loc[pr.cve].copy()
d["p"] = pr.p.to_numpy()
assert (d.bump_up.astype(int).to_numpy() == pr.y.to_numpy()).all(), "labels differ from the M4 predictions"
assert len(d) == serving["test_eval_rows"]["n"], "not the 2026 evaluation rows of serving_stack.json"
d["band"] = np.where(d.p >= tau, "likely", np.where(d.p >= tau_possible, "possible", "unlikely"))
# sanity: same band counts as the served model's evidence file
for b, v in serving["test_eval_rows"]["bands"].items():
    assert int((d.band == b).sum()) == v["n"], f"band {b} count differs from serving_stack.json"
d["llm_vector"] = [llm.get(c) for c in d.index]
d["our_vector"] = np.where(d.p >= gate_t, d.llm_vector, d.cna_vector)
y = d.bump_up.astype(bool)

fp_pool = d[(d.band == "likely") & ~y]
fn_pool = d[y & (d.band != "likely")]
rng = np.random.default_rng(0)
fp = fp_pool.loc[rng.choice(fp_pool.index, size=min(a.n, len(fp_pool)), replace=False)].sort_values("p", ascending=False)
fn = fn_pool.loc[rng.choice(fn_pool.index, size=min(a.n, len(fn_pool)), replace=False)].sort_values("p", ascending=False)


def sev(v):
    if not isinstance(v, str):
        return "—"
    s = base_score(parse(v))
    return f"{severity(s)} {s}"


def case(i, cve, r):
    desc = " ".join(str(r.description).split())
    nvd = r.nvd_vector if isinstance(r.nvd_vector, str) else None
    return "\n".join([
        f"### {i}. {cve}",
        "",
        f"- Published {r.published} · scorer `{r.cna}` ({r.score_source}) · CNA CWE {r.cna_cwe or '—'}",
        f"- Band **{r.band}** (stack p_bump {r.p:.3f}; likely ≥ {tau:.3f}, gate ≥ {gate_t:.3f})",
        "",
        "| | Vector | Severity |",
        "|---|---|---|",
        f"| CNA | `{r.cna_vector}` | {sev(r.cna_vector)} |",
        f"| NVD | `{nvd}` | {sev(nvd)} |" if nvd else
        "| NVD | — (kept the CNA vector; label = CNA) | — |",
        f"| Ours (served) | `{r.our_vector}` | {sev(r.our_vector)} |",
        f"| Fine-tuned LLM (raw) | `{r.llm_vector}` | {sev(r.llm_vector)} |",
        "",
        f"> {desc}",
        "",
        "Tag: ",
        "",
    ])


lines = [
    "# Error analysis sample (served combined model, 2026 evaluation rows)",
    "",
    f"Evaluation snapshot: NVD data as of {AS_OF}. Model: {serving['model']}, from `{a.preds}`. Rows: the "
    f"{len(d):,} 2026 test CVEs with a fine-tuned-LLM prediction (base rate {y.mean():.3f}). Generated by "
    "`scripts/10_error_analysis.py` (random sample, seed 0; within each section sorted by p_bump).",
    "",
    f"- **False positives:** band \"likely\" (p ≥ τ = {tau:.3f}) but NVD did not raise the band: "
    f"{len(fp_pool)} of {int((d.band == 'likely').sum())} \"likely\" rows; {len(fp)} sampled.",
    f"- **False negatives:** NVD raised the band but our band is not \"likely\": {len(fn_pool)} of {int(y.sum())} "
    f"raised rows ({int((fn_pool.band == 'possible').sum())} \"possible\", "
    f"{int((fn_pool.band == 'unlikely').sum())} \"unlikely\"); {len(fn)} sampled "
    f"({int((fn.band == 'possible').sum())} \"possible\", {int((fn.band == 'unlikely').sum())} \"unlikely\").",
    "- **Ours (served)** = the fine-tuned LLM vector if p ≥ the gate threshold, otherwise the CNA vector.",
    "",
    "**Tag each case [HUMAN]** with one of: `model wrong` / `NVD worst-casing` / `ambiguous description` / "
    "`label noise`.",
    "",
    "## False positives (flagged \"likely\", NVD did not raise)",
    "",
]
lines += [case(i, c, r) for i, (c, r) in enumerate(fp.iterrows(), 1)]
lines += ["## False negatives (NVD raised, not flagged \"likely\")", ""]
lines += [case(i, c, r) for i, (c, r) in enumerate(fn.iterrows(), len(fp) + 1)]
Path(a.out).write_text("\n".join(lines), encoding="utf-8")
print(f"wrote {a.out}: {len(fp)} FP (pool {len(fp_pool)}), {len(fn)} FN (pool {len(fn_pool)})")
